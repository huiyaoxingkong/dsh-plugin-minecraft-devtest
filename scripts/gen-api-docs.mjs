// Generate docs/API.md from the plugin source.
//
//   npm run gen:docs
//
// The tool list is parsed from index.js (name + description of every
// `resultTool(...)` registration); module/topic sections are curated below.
// Keeping this file as the single generator avoids stale copies of the tool
// list in the docs.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = readFileSync(new URL('../index.js', import.meta.url), 'utf8');

const tools = [];
const toolPattern = /ctx\.tools\.register\(\s*resultTool\(\s*'([^']+)',\s*'((?:[^'\\]|\\.)*)'/g;
for (const match of source.matchAll(toolPattern)) {
  const description = match[2].replace(/\\'/g, "'").replace(/\\\\/g, '\\');
  tools.push({ name: match[1], description });
}

const modules = [
  ['index.js', 'DSH tool registration (`inject: [\'tools\']`) and tool handlers'],
  ['lib/server.js', 'Headless server lifecycle: jar/fabric/script/gradle, launcher detection, version/loader inference, Java selection, RCON-ready, properties patching'],
  ['lib/rcon.js', 'Minecraft RCON client (auth, command, timeout, reconnect-safe close)'],
  ['lib/bot.js', 'Unified player-bot entry: native (Mineflayer), emulated (26.2/26.3), legacy (1.7.x), emulated-future (26.4) dispatch'],
  ['lib/protocol-compat.js', 'Idempotent installer for the bundled upstream 26.x protocol payload and Mineflayer version window widening'],
  ['lib/legacy-bot.js', 'Native 1.7.10 protocol bot: join/chat/look/goto/dig/place/use/attack/wait'],
  ['lib/datapack.js', 'Datapack scan/validate/deploy/list and server jar `version.json` detection'],
  ['lib/cards.js', 'Minimal YAML test-card parser and deterministic executor (assert/command/bot/datapack steps)'],
  ['lib/quickcheck.js', 'One-call health check: validate, start, RCON, deploy/reload, log scan, bot smoke'],
  ['lib/gradle.js', 'Gradle task runner with GameTest summary parsing'],
  ['lib/guide.js', 'Built-in knowledge base (topics: overview/cards/datapack/bot/server/errors/versions)'],
  ['lib/init.js', 'Scaffolds test cards from a datapack / mod project'],
  ['lib/bridge.js', 'Bundled Forge 1.20.1 test bridge detection/install'],
  ['lib/versions.js', 'Official release registry (1.7.10–26.4), Java matrix, data-pack formats, JDK scanning'],
  ['lib/util.js', 'Shared helpers (log parsing, command normalization, file tails, process helpers)'],
  ['vendor/upstream-26.3/', 'Bundled unmodified PrismarineJS 26.3 PR sources + minecraft-data 26.2/26.3 data'],
  ['vendor/forge-bridge/', 'Own dedicated Forge 1.20.1 server-side test bridge mod (source + prebuilt jar)'],
  ['scripts/gen-versions.mjs', 'Regenerates lib/versions.js from Mojang piston-meta'],
  ['scripts/gen-api-docs.mjs', 'Regenerates this document from index.js'],
];

const today = new Date().toISOString().slice(0, 10);
const lines = [];
lines.push('# API reference (generated)');
lines.push('');
lines.push(`> Generated by \`npm run gen:docs\` on ${today} from \`index.js\`. Do not edit the tool table by hand.`);
lines.push('');
lines.push('`dsh-plugin-minecraft-devtest` is a DeepSeek Harness (DSH) plugin. It injects 12 model-facing tools;');
lines.push('all server-side work happens locally in the plugin, so the model only receives compact results.');
lines.push('');
lines.push(`## Tools (${tools.length})`);
lines.push('');
lines.push('| Tool | Purpose |');
lines.push('| --- | --- |');
for (const tool of tools) {
  lines.push(`| \`${tool.name}\` | ${tool.description.replace(/\|/g, '\\|')} |`);
}
lines.push('');
lines.push('Parameter schemas are registered with DSH and are discoverable by the model automatically.');
lines.push('Examples live in [README](../README.md), [guide.js](../lib/guide.js) and `examples/`.');
lines.push('');
lines.push('## Modules');
lines.push('');
lines.push('| Path | Responsibility |');
lines.push('| --- | --- |');
for (const [file, purpose] of modules) {
  lines.push(`| \`${file}\` | ${purpose} |`);
}
lines.push('');
lines.push('## Version support');
lines.push('');
lines.push('- Server lifecycle: official releases **1.7.10 – 26.3**, 26.4 forward-compatible; Java auto-selected (8/16/17/21/25).');
lines.push('- Datapacks: **1.13+** (1.7.10–1.12.2 clearly unsupported); pack formats are read from the server jar or `lib/versions.js`,');
lines.push('  including 1.21.9+ `min_format`/`max_format` handling.');
lines.push('- Bot: `1.7.x` legacy, `1.8.8–26.1` native Mineflayer, `26.2/26.3` bundled upstream compatibility layer, `26.4` best effort.');
lines.push('- Loaders: Forge/Fabric/NeoForge/Quilt server installs are detected and launched in all supported launch forms.');
lines.push('');
lines.push('## Documentation map');
lines.push('');
lines.push('| Document | Content |');
lines.push('| --- | --- |');
lines.push('| [README](../README.md) | Install, tools, quickstart, compatibility and limits |');
lines.push('| [docs/LOADERS.md](./LOADERS.md) | Mod-loader coverage and verified combinations |');
lines.push('| [docs/TESTING.md](./TESTING.md) | Verification report (tests, E2E matrices, evidence) |');
lines.push('| [docs/CONTRACTS.md](./CONTRACTS.md) | Internal module contracts |');
lines.push('| [docs/REQUIREMENTS.md](./REQUIREMENTS.md) | Requirements and acceptance criteria |');
lines.push('| [THIRD_PARTY_NOTICES.md](../THIRD_PARTY_NOTICES.md) | Open-source attribution |');
lines.push('');
lines.push('## Safety boundary');
lines.push('');
lines.push('The plugin only ever controls the one test server started by `mcdt_server` in this session.');
lines.push('Bot/command/datapack actions reject arbitrary host/port or externally running servers.');
lines.push('Start any test server with `online-mode=false`; the plugin patches EULA/RCON/whitelist for you.');
lines.push('');

writeFileSync(new URL('../docs/API.md', import.meta.url), lines.join('\n'), 'utf8');
console.log(`docs/API.md written: ${tools.length} tools, ${modules.length} modules, source ${source.length} bytes, root ${root}`);
